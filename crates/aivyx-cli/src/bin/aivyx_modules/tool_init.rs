//! `aivyx-pa tool init <path>` — Phase 103.
//!
//! Writes a runnable Rust tool-process starter project to a
//! target directory. The author edits one function body
//! (`handle_invocation`) and has a buildable, conformance-tested
//! starting point; everything else is protocol scaffolding.
//!
//! The scaffold depends on the existing `aivyx-tool` crate
//! (already re-exports the wire types and length-prefixed
//! framing), so this phase ships *no new SDK helper* — just a
//! generator for a project that links against the substrate
//! that is already there.
//!
//! Templates are embedded as inline string constants rather
//! than `include_str!`'d from `examples/templates/tool/` because
//! the template `src/main.rs` is itself Rust source and would
//! otherwise be picked up by tooling that walks the workspace.
//! A single `r##"..."##` constant per file keeps everything
//! contained in this module.

use std::fs;
use std::path::Path;

/// The four files the scaffold writes, in deterministic order.
const FILES: &[(&str, &str)] = &[
    ("Cargo.toml", CARGO_TOML),
    ("src/main.rs", MAIN_RS),
    ("README.md", README_MD),
    ("tests/conformance.rs", CONFORMANCE_RS),
];

/// `aivyx-pa tool init <path> [--force]`
pub fn run_tool_init(target: &Path, force: bool) -> Result<(), String> {
    // Target dir state: either does not exist (we create it) or
    // exists and is empty (we write into it), or exists and is
    // non-empty (refuse unless --force). A `force` write does
    // NOT delete pre-existing files at the same names; it only
    // bypasses the non-empty refusal.
    if target.exists() {
        if !target.is_dir() {
            return Err(format!(
                "aivyx-pa tool init: {target:?} exists and is not a \
                 directory"
            ));
        }
        let non_empty = fs::read_dir(target)
            .map_err(|e| format!("cannot read {target:?}: {e}"))?
            .next()
            .is_some();
        if non_empty && !force {
            return Err(format!(
                "aivyx-pa tool init: {target:?} is not empty; pass \
                 `--force` to write into it anyway"
            ));
        }
    } else {
        fs::create_dir_all(target).map_err(|e| format!("cannot create {target:?}: {e}"))?;
    }

    for (rel, content) in FILES {
        let path = target.join(rel);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)
                .map_err(|e| format!("cannot create parent of {path:?}: {e}"))?;
        }
        fs::write(&path, content).map_err(|e| format!("cannot write {path:?}: {e}"))?;
    }

    println!(
        "aivyx-pa tool init: scaffolded a Rust tool-process project at \
         {target:?}"
    );
    println!();
    println!("Next steps:");
    println!(
        "  1. Edit {0}/Cargo.toml — replace REPLACE_WITH_PATH_TO_AIVYX",
        target.display()
    );
    println!("     with the absolute path to your aivyx clone.");
    println!(
        "  2. Edit {0}/src/main.rs — replace the body of",
        target.display()
    );
    println!("     `handle_invocation` with your tool's real work.");
    println!("  3. Build:  cargo build --release");
    println!("  4. Add to your aivyx-pa.toml:");
    println!();
    println!("{TOOL_PROCESS_SNIPPET}");
    Ok(())
}

