const MAIN_RS: &str = r##"//! Aivyx tool process — handler stub generated by
//! `aivyx-pa tool init`.
//!
//! Replace the body of `handle_invocation` with your tool's
//! real work. Optionally edit `descriptor()` to match your
//! tool's name, description, input schema, and required
//! scope. The rest of this file is protocol scaffolding you
//! should not need to touch.

use aivyx_tool::frame::{read_frame, write_frame};
use aivyx_tool::wire::{
    DaemonToTool, ToolDescriptor, ToolToDaemon, Verification,
};
use serde_json::{json, Value};
use tokio::io::{stdin, stdout};

const TOOL_NAME: &str = "my_tool";

/// The single tool this process exposes. Edit `name`,
/// `description`, `input_schema`, and `required_scope` to fit
/// your tool. The planner sees this descriptor.
fn descriptor() -> ToolDescriptor {
    ToolDescriptor {
        name: TOOL_NAME.to_string(),
        description: "A starter tool — replace me.".to_string(),
        input_schema: json!({
            "type": "object",
            "properties": { "text": { "type": "string" } },
            "required": ["text"]
        }),
        // `memory.read` is the narrowest pre-registered scope a
        // starter can hold without authoring a new capability
        // base. Change this once your tool's real capability
        // shape is known — the operator's role envelope must
        // grant whatever scope you declare here.
        required_scope: "memory.read".to_string(),
    }
}

/// EDIT THIS. Your tool's real work goes here. The input
/// shape must match `descriptor().input_schema`; the return
/// shape is whatever your tool emits.
fn handle_invocation(input: Value) -> Result<Value, String> {
    let text = input
        .get("text")
        .and_then(|v| v.as_str())
        .ok_or_else(|| "`text` field is required".to_string())?;
    Ok(json!({
        "echoed": text,
        "length": text.len(),
    }))
}

#[tokio::main(flavor = "current_thread")]
async fn main() -> std::io::Result<()> {
    let mut stdin = stdin();
    let mut stdout = stdout();

    // Handshake: ToolHello -> ToolRegister.
    let hello = read_message(&mut stdin)
        .await
        .map_err(io_err)?
        .ok_or_else(|| io_err("expected ToolHello, got EOF"))?;
    match hello {
        DaemonToTool::ToolHello { .. } => {}
        other => {
            return Err(io_err(format!(
                "expected ToolHello, got {other:?}"
            )));
        }
    }
    write_message(
        &mut stdout,
        &ToolToDaemon::ToolRegister {
            tool_process_name: TOOL_NAME.to_string(),
            tools: vec![descriptor()],
        },
    )
    .await
    .map_err(io_err)?;

    // Per-invocation loop.
    loop {
        let msg = match read_message(&mut stdin).await.map_err(io_err)? {
            Some(m) => m,
            None => return Ok(()), // clean EOF — daemon closed our stdin
        };
        match msg {
            DaemonToTool::ToolHello { .. } => {
                // Out-of-band ToolHello after the handshake is
                // not part of the protocol; skip gracefully.
            }
            DaemonToTool::ToolShutdown => return Ok(()),
            DaemonToTool::CancelInvocation { call_id } => {
                let _ = write_message(
                    &mut stdout,
                    &ToolToDaemon::ToolError {
                        call_id,
                        code: "cancelled".to_string(),
                        message: format!("{TOOL_NAME} was cancelled"),
                    },
                )
                .await;
            }
            DaemonToTool::InvokeTool {
                call_id,
                tool_name,
                input,
                ..
            } => {
                let reply = if tool_name != TOOL_NAME {
                    ToolToDaemon::ToolError {
                        call_id,
                        code: "unknown_tool".to_string(),
                        message: format!(
                            "this process does not implement {tool_name}"
                        ),
                    }
                } else {
                    match handle_invocation(input) {
                        Ok(output) => ToolToDaemon::ToolResult {
                            call_id,
                            verified: Verification::NotApplicable,
                            output,
                        },
                        Err(e) => ToolToDaemon::ToolError {
                            call_id,
                            code: "invocation_failed".to_string(),
                            message: e,
                        },
                    }
                };
                write_message(&mut stdout, &reply)
                    .await
                    .map_err(io_err)?;
            }
        }
    }
}

// ---- protocol helpers ---------------------------------------------

async fn read_message<R: tokio::io::AsyncReadExt + Unpin>(
    r: &mut R,
) -> Result<Option<DaemonToTool>, String> {
    let Some(text) = read_frame(r).await.map_err(|e| e.to_string())? else {
        return Ok(None);
    };
    let msg: DaemonToTool = serde_json::from_str(&text)
        .map_err(|e| format!("decode DaemonToTool: {e}"))?;
    Ok(Some(msg))
}

async fn write_message<W: tokio::io::AsyncWrite + Unpin>(
    w: &mut W,
    msg: &ToolToDaemon,
) -> Result<(), String> {
    write_frame(w, msg).await.map_err(|e| e.to_string())
}

fn io_err<E: std::fmt::Display>(e: E) -> std::io::Error {
    std::io::Error::other(e.to_string())
}
"##;

const README_MD: &str = r##"# My Aivyx tool

A starter Aivyx tool-process scaffold generated by
`aivyx-pa tool init`. Edit `src/main.rs` — replace the body of
`handle_invocation` (and optionally adjust `descriptor()`) to
do your tool's real work.

## Build

```sh
cargo build --release
```

The binary lands at `target/release/my-aivyx-tool`.

## Wire it into Aivyx

Add a `[[tool_process]]` block to your `aivyx-pa.toml`:

```toml
[[tool_process]]
name = "my-aivyx-tool"
command = "/abs/path/to/target/release/my-aivyx-tool"
```

The Aivyx daemon will spawn this process at startup, perform
the `ToolHello` → `ToolRegister` handshake, validate the
declared `required_scope` against your active role's envelope,
and then route any matching tool calls to your
`handle_invocation`.

## Conformance test

```sh
cargo test
```

Drives the wire types this scaffold links against and proves
a `ToolResult` round-trips through the framing — if the
underlying protocol changes incompatibly, this test stops
compiling.

## Reference

See `docs/TOOL_SDK.md` in the Aivyx repository for the full
tool-process protocol contract — what the daemon sends, what
your process is expected to send back, lifecycle, sandboxing,
and the trust model.
"##;

const CONFORMANCE_RS: &str = r##"//! Daemon-free conformance smoke test for the scaffolded
//! Aivyx tool process. The point of this test is *not* to
//! exercise your tool's logic — it is to assert that the wire
//! types this project links against compile and round-trip,
//! so an incompatible change to the underlying `aivyx-tool`
//! crate fails the test rather than the live integration.

use aivyx_tool::frame::{read_frame, write_frame};
use aivyx_tool::wire::{DaemonToTool, ToolToDaemon, Verification};
use serde_json::json;
use tokio::io::duplex;

#[tokio::test]
async fn wire_types_compile_and_round_trip() {
    // Construct one of every kind the scaffold's main loop
    // touches — if any variant or field renames upstream, the
    // test fails to compile.
    let _hello = DaemonToTool::ToolHello {
        protocol_version: "0.1".to_string(),
    };
    let _invoke = DaemonToTool::InvokeTool {
        call_id: "c1".to_string(),
        tool_name: "my_tool".to_string(),
        input: json!({"text": "hi"}),
        turn_id: "t1".to_string(),
    };
    let _shutdown = DaemonToTool::ToolShutdown;
    let _cancel = DaemonToTool::CancelInvocation {
        call_id: "c1".to_string(),
    };

    // Round-trip a ToolResult through the length-prefixed
    // framing over an in-memory duplex pipe.
    let (mut a, mut b) = duplex(1024);
    let outgoing = ToolToDaemon::ToolResult {
        call_id: "c2".to_string(),
        verified: Verification::NotApplicable,
        output: json!({"hello": "world"}),
    };
    write_frame(&mut a, &outgoing).await.unwrap();
    let frame_text = read_frame(&mut b).await.unwrap().expect("frame present");
    let decoded: ToolToDaemon = serde_json::from_str(&frame_text).unwrap();
    assert_eq!(decoded, outgoing);
}
"##;

