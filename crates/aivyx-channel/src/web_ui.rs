/// Run the web UI server. Binds `<host>:<port>` (default host
/// `127.0.0.1`), serves the embedded HTML at `GET /`, and upgrades
/// `GET /ws` to WebSocket. Each WS connection bridges to the daemon's
/// Unix socket at `socket_path`.
///
/// `host` is `None` for the default localhost-only posture every native
/// install keeps; Chapter Harbor passes `0.0.0.0` for containerized
/// deployment (Docker forwards published ports to the container's
/// `0.0.0.0`, not its loopback). Binding beyond loopback is a deliberate
/// network exposure — the WS Origin allowlist (below) still defends
/// against CSWSH / DNS-rebinding, and operators front it with auth/TLS.
///
/// Uses `tokio-tungstenite` directly on the TCP stream — each
/// incoming connection is peeked to determine if it's a WebSocket
/// upgrade request for `/ws` or an HTTP request for `/`. This
/// avoids pulling hyper into the WebSocket path.
///
/// This future never returns normally — it runs until `shutdown` is
/// cancelled.
#[allow(clippy::too_many_arguments)]
pub async fn run_web_ui_server(
    socket_path: PathBuf,
    host: Option<std::net::IpAddr>,
    port: u16,
    allowed_origins: Vec<String>,
    auth_token: Option<String>,
    comfyui_base_url: Option<String>,
    shutdown: CancellationToken,
    web_ui_broadcaster: Option<Arc<WebUiBroadcaster>>,
) -> Result<(), DaemonError> {
    let host = host.unwrap_or(std::net::IpAddr::V4(std::net::Ipv4Addr::LOCALHOST));
    let addr = std::net::SocketAddr::new(host, port);
    let allowed_origins = Arc::new(allowed_origins);
    let auth_token = Arc::new(auth_token);
    let comfyui_base_url = Arc::new(comfyui_base_url);

    // Chapter Harbor F-4 — binding beyond loopback is a deliberate network
    // exposure. Warn once at startup so an operator who flips web_ui_host can't
    // miss that the Studio (a powerful agent) is now reachable off-host.
    if !host.is_loopback() {
        eprintln!(
            "aivyx web ui: WARNING — binding {host} (non-loopback). The Studio \
             is exposed beyond this host. Put TLS in front, and set \
             `[daemon] web_ui_allowed_origins` for the hostnames you serve. See \
             docs/DOCKER.md."
        );
        // Chapter Postern — off-host with no token is an unauthenticated
        // control plane. Escalate the warning; don't refuse (a reverse proxy
        // may add auth), but make the exposure impossible to miss.
        if auth_token.is_none() {
            eprintln!(
                "aivyx web ui: WARNING — no `[daemon] web_ui_auth_token` set \
                 while bound off-host: ANYONE who can reach {addr} can drive \
                 the agent, read memory, and change config. Set a token."
            );
        }
    }
    if auth_token.is_some() {
        eprintln!("aivyx web ui: auth token required for the control plane (/ws)");
    }
    let listener = TcpListener::bind(addr)
        .await
        .map_err(|source| DaemonError::Bind {
            path: addr.to_string(),
            source,
        })?;

    eprintln!("aivyx web ui: listening on http://{addr}");

    let socket_path = Arc::new(socket_path);

    loop {
        let (stream, _remote) = tokio::select! {
            result = listener.accept() => {
                match result {
                    Ok(conn) => conn,
                    Err(e) => {
                        eprintln!("aivyx web ui: accept error: {e}");
                        continue;
                    }
                }
            }
            _ = shutdown.cancelled() => return Ok(()),
        };

        let conn_socket_path = Arc::clone(&socket_path);
        let conn_broadcaster = web_ui_broadcaster.clone();
        let conn_allowed_origins = Arc::clone(&allowed_origins);
        let conn_auth_token = Arc::clone(&auth_token);
        let conn_comfyui_base_url = Arc::clone(&comfyui_base_url);

        tokio::spawn(async move {
            if let Err(e) = handle_connection(
                stream,
                &conn_socket_path,
                port,
                &conn_allowed_origins,
                conn_auth_token.as_deref(),
                conn_comfyui_base_url.as_deref(),
                conn_broadcaster,
            )
            .await
            {
                eprintln!("aivyx web ui: connection error: {e}");
            }
        });
    }
}

