//! Phase 182 — guided in-agent credential onboarding.
//!
//! `aivyx connect [service]` turns the undocumented "create a
//! Google Cloud OAuth app → hand-write `config.toml` → run a
//! separate `aivyx-<service>` binary's `auth init` → wire
//! `[[tool_process]]`" sequence into one guided command.
//!
//! This module owns the *pure* pieces — the service registry,
//! the `config.toml` writer, the per-service paths, and the
//! connected-status check. The guided flow (Task 3) and the
//! `[[tool_process]]` auto-wire (Task 4) build on top. The OAuth
//! dance itself stays in the per-service `auth init` (we shell
//! out to it) and is operator-verified, not unit-tested.

// Phase 182 — the guided flow (Task 3) + tool_process auto-wire
// (Task 4) consume this API; the allow is removed when wired.
#![allow(dead_code)]

use std::path::{Path, PathBuf};

/// A connectable Google OAuth service. The registry is the source
/// of truth for what `aivyx connect` can onboard; Notion / n8n
/// (API-key paste) are a deferred follow-on.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ConnectService {
    /// Stable key — the `~/.aivyx/tool-processes/<key>/` subdir
    /// and the CLI argument (`aivyx connect <key>`).
    pub key: &'static str,
    /// Operator-facing name.
    pub display: &'static str,
    /// The tool-process binary whose `auth init` runs the dance.
    pub binary: &'static str,
    /// The Google Cloud API the operator must enable.
    pub google_api: &'static str,
    /// The loopback port the consent redirect lands on. Desktop
    /// OAuth clients accept any loopback port; a fixed default
    /// keeps the operator's registered redirect_uri stable.
    pub redirect_port: u16,
}

/// The connectable Google services (Phase 182).
pub const SERVICES: &[ConnectService] = &[
    ConnectService {
        key: "gmail",
        display: "Gmail",
        binary: "aivyx-gmail",
        google_api: "Gmail API",
        redirect_port: 8765,
    },
    ConnectService {
        key: "calendar",
        display: "Google Calendar",
        binary: "aivyx-calendar",
        google_api: "Google Calendar API",
        redirect_port: 8766,
    },
    ConnectService {
        key: "drive",
        display: "Google Drive",
        binary: "aivyx-drive",
        google_api: "Google Drive API",
        redirect_port: 8767,
    },
];

/// Look up a service by its key (case-insensitive).
pub fn find_service(key: &str) -> Option<&'static ConnectService> {
    let k = key.trim().to_ascii_lowercase();
    SERVICES.iter().find(|s| s.key == k)
}

impl ConnectService {
    /// The loopback redirect URI written into `config.toml` and
    /// registered against the operator's Google Cloud OAuth app.
    pub fn redirect_uri(&self) -> String {
        format!("http://127.0.0.1:{}/callback", self.redirect_port)
    }

    /// `~/.aivyx/tool-processes/<key>/` — the per-tool-process dir
    /// (the same one the service binary + the Phase 180 sandbox
    /// preset use).
    pub fn process_dir(&self, home: &Path) -> PathBuf {
        home.join(".aivyx").join("tool-processes").join(self.key)
    }

    pub fn config_path(&self, home: &Path) -> PathBuf {
        self.process_dir(home).join("config.toml")
    }

    pub fn token_path(&self, home: &Path) -> PathBuf {
        self.process_dir(home).join("tokens.json")
    }

    /// Connected iff a `tokens.json` exists (the per-service
    /// `auth init` wrote it after a successful consent).
    pub fn is_connected(&self, home: &Path) -> bool {
        self.token_path(home).exists()
    }
}

/// Render the minimal OAuth `config.toml` the service binary
/// loads. Scopes are omitted on purpose — each service's
/// `load_oauth_config` injects its own `DEFAULT_*_SCOPES` when the
/// field is absent, so the operator never has to know scope URLs.
pub fn render_oauth_config_toml(
    client_id: &str,
    client_secret: &str,
    redirect_uri: &str,
) -> String {
    format!(
        "# Generated by `aivyx connect`. Operator-provided OAuth \
         app credentials.\n\
         # client_secret is sensitive; this file is written 0600.\n\
         client_id = \"{}\"\n\
         client_secret = \"{}\"\n\
         redirect_uri = \"{}\"\n",
        escape(client_id),
        escape(client_secret),
        escape(redirect_uri),
    )
}

fn escape(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

/// Write the OAuth `config.toml` for `service` under `home`,
/// creating the per-tool-process dir and chmod'ing the file to
/// `0600`. Returns the path written.
pub fn write_oauth_config(
    service: &ConnectService,
    home: &Path,
    client_id: &str,
    client_secret: &str,
) -> Result<PathBuf, String> {
    let dir = service.process_dir(home);
    std::fs::create_dir_all(&dir)
        .map_err(|e| format!("failed to create {}: {e}", dir.display()))?;
    let path = service.config_path(home);
    let body = render_oauth_config_toml(
        client_id,
        client_secret,
        &service.redirect_uri(),
    );
    std::fs::write(&path, body)
        .map_err(|e| format!("failed to write {}: {e}", path.display()))?;
    set_file_0600(&path);
    Ok(path)
}

#[cfg(unix)]
fn set_file_0600(path: &Path) {
    use std::os::unix::fs::PermissionsExt;
    let _ = std::fs::set_permissions(
        path,
        std::fs::Permissions::from_mode(0o600),
    );
}

#[cfg(not(unix))]
fn set_file_0600(_path: &Path) {}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn registry_lookup_is_case_insensitive_and_total() {
        assert_eq!(find_service("gmail").unwrap().binary, "aivyx-gmail");
        assert_eq!(find_service("  Drive ").unwrap().key, "drive");
        assert_eq!(
            find_service("CALENDAR").unwrap().display,
            "Google Calendar"
        );
        assert!(find_service("notion").is_none()); // deferred
        assert!(find_service("nope").is_none());
        // Every service has a distinct loopback port.
        let mut ports: Vec<u16> =
            SERVICES.iter().map(|s| s.redirect_port).collect();
        ports.sort();
        ports.dedup();
        assert_eq!(ports.len(), SERVICES.len());
    }

    #[test]
    fn paths_anchor_under_the_tool_process_dir() {
        let svc = find_service("gmail").unwrap();
        let home = Path::new("/home/op");
        assert_eq!(
            svc.config_path(home),
            Path::new("/home/op/.aivyx/tool-processes/gmail/config.toml")
        );
        assert_eq!(
            svc.token_path(home),
            Path::new("/home/op/.aivyx/tool-processes/gmail/tokens.json")
        );
        assert_eq!(
            svc.redirect_uri(),
            "http://127.0.0.1:8765/callback"
        );
    }

    #[test]
    fn config_toml_renders_minimal_and_escapes() {
        let s = render_oauth_config_toml(
            "id.apps.googleusercontent.com",
            "sec\"ret\\x",
            "http://127.0.0.1:8765/callback",
        );
        // Parses as valid TOML with the three fields, no scopes.
        let doc: toml_edit::DocumentMut = s.parse().expect("valid TOML");
        assert_eq!(
            doc["client_id"].as_str(),
            Some("id.apps.googleusercontent.com")
        );
        assert_eq!(doc["client_secret"].as_str(), Some("sec\"ret\\x"));
        assert_eq!(
            doc["redirect_uri"].as_str(),
            Some("http://127.0.0.1:8765/callback")
        );
        assert!(doc.get("scopes").is_none());
    }

    #[test]
    fn write_then_connected_check_round_trips() {
        let tmp = std::env::temp_dir()
            .join(format!("aivyx-connect-{}", uuid::Uuid::new_v4()));
        let svc = find_service("calendar").unwrap();
        // Not connected before, and no config yet.
        assert!(!svc.is_connected(&tmp));
        let path =
            write_oauth_config(svc, &tmp, "the-id", "the-secret").unwrap();
        assert!(path.exists());
        let body = std::fs::read_to_string(&path).unwrap();
        assert!(body.contains("client_id = \"the-id\""));
        assert!(body.contains("127.0.0.1:8766")); // calendar's port
        // Still "not connected" — config exists but no tokens.json.
        assert!(!svc.is_connected(&tmp));
        // Simulate a successful auth init writing tokens.json.
        std::fs::write(svc.token_path(&tmp), "{}").unwrap();
        assert!(svc.is_connected(&tmp));
        let _ = std::fs::remove_dir_all(&tmp);
    }
}
