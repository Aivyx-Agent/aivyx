/// Cookie name the browser carries back on the `/ws` upgrade (it cannot set
/// request headers on `new WebSocket()`, but same-origin cookies ARE sent on
/// the handshake). Planted on the Basic-Auth'd page load.
const AUTH_COOKIE: &str = "aivyx_web_token";

/// Constant-time byte comparison — avoids leaking the token length/prefix via
/// early-exit timing on a shared secret.
fn ct_eq(a: &[u8], b: &[u8]) -> bool {
    if a.len() != b.len() {
        return false;
    }
    let mut diff = 0u8;
    for (x, y) in a.iter().zip(b.iter()) {
        diff |= x ^ y;
    }
    diff == 0
}

/// First value of a header (case-insensitive name) from a peeked request head.
fn header_value<'a>(request_head: &'a str, name: &str) -> Option<&'a str> {
    request_head.split("\r\n").find_map(|line| {
        line.split_once(':')
            .and_then(|(n, v)| n.trim().eq_ignore_ascii_case(name).then(|| v.trim()))
    })
}

/// `Authorization: Bearer <token>` (non-browser clients).
fn bearer_token(request_head: &str) -> Option<&str> {
    header_value(request_head, "authorization")?
        .strip_prefix("Bearer ")
        .map(str::trim)
}

/// The password half of `Authorization: Basic base64(user:pass)` — how a
/// browser sends the token after the native Basic-Auth prompt.
fn basic_password(request_head: &str) -> Option<String> {
    use base64::Engine;
    let b64 = header_value(request_head, "authorization")?.strip_prefix("Basic ")?;
    let decoded = base64::engine::general_purpose::STANDARD
        .decode(b64.trim())
        .ok()?;
    let creds = String::from_utf8(decoded).ok()?;
    // user:pass — the token is the password (user is ignored).
    creds.split_once(':').map(|(_, pass)| pass.to_string())
}

/// The [`AUTH_COOKIE`] value from the `Cookie` header, if present.
fn cookie_token(request_head: &str) -> Option<String> {
    let cookies = header_value(request_head, "cookie")?;
    cookies.split(';').find_map(|kv| {
        let (k, v) = kv.split_once('=')?;
        (k.trim() == AUTH_COOKIE).then(|| v.trim().to_string())
    })
}

/// True when the request presents the valid token by ANY accepted means:
/// a Bearer header, HTTP Basic password, or the auth cookie.
fn request_carries_token(request_head: &str, token: &str) -> bool {
    let tb = token.as_bytes();
    if bearer_token(request_head).is_some_and(|t| ct_eq(t.as_bytes(), tb)) {
        return true;
    }
    if basic_password(request_head).is_some_and(|p| ct_eq(p.as_bytes(), tb)) {
        return true;
    }
    if cookie_token(request_head).is_some_and(|c| ct_eq(c.as_bytes(), tb)) {
        return true;
    }
    false
}

/// Handle a single TCP connection. Peek at the first bytes to
/// determine the HTTP path, then either serve HTML or upgrade to
/// WebSocket.
async fn handle_connection(
    stream: tokio::net::TcpStream,
    socket_path: &Path,
    port: u16,
    allowed_origins: &[String],
    auth_token: Option<&str>,
    comfyui_base_url: Option<&str>,
    web_ui_broadcaster: Option<Arc<WebUiBroadcaster>>,
) -> Result<(), DaemonError> {
    // Peek at the request head to determine the path *and* read the
    // `Origin` header for the WebSocket origin check. 4 KiB comfortably
    // covers a standard handshake's request line + headers.
    let mut peek_buf = [0u8; 4096];
    let n = stream.peek(&mut peek_buf).await?;
    let request_head = String::from_utf8_lossy(&peek_buf[..n]);

    if request_head.starts_with("GET /ws") {
        // Chapter Postern — the /ws upgrade IS the control plane (agent turns,
        // config writes, memory reads all flow over it). When a token is set it
        // is REQUIRED here, before the origin check even matters. A browser
        // cannot set headers on `new WebSocket()`, so it authenticates via the
        // cookie planted during the Basic-Auth'd page load; a non-browser
        // client can send `Authorization: Bearer <token>` directly.
        if let Some(token) = auth_token {
            if !request_carries_token(&request_head, token) {
                return serve_bytes(
                    stream,
                    "401 Unauthorized",
                    "text/plain; charset=utf-8",
                    b"unauthorized: web UI auth token required",
                )
                .await;
            }
        }
        // CSWSH / DNS-rebinding defense: a browser *always* sends `Origin` on a
        // WebSocket handshake, so a cross-site page trying to drive this
        // localhost daemon (which can write config + the filesystem) is
        // detectable. Reject any `Origin` that isn't one of our own loopback
        // origins on the bound port. A missing `Origin` is a non-browser client
        // (the CLI / Python IPC probe / native apps) and is allowed — those can
        // already reach the Unix socket directly, so they're inside the trust
        // boundary regardless.
        if !ws_origin_allowed(&request_head, port, allowed_origins) {
            return serve_bytes(
                stream,
                "403 Forbidden",
                "text/plain; charset=utf-8",
                b"forbidden: cross-origin websocket rejected",
            )
            .await;
        }

        // WebSocket upgrade — let tokio-tungstenite handle the
        // HTTP 101 handshake and the WebSocket framing.
        let ws_stream = tokio_tungstenite::accept_async(stream)
            .await
            .map_err(|e| DaemonError::WebSocket(format!("ws handshake: {e}")))?;

        handle_websocket(ws_stream, socket_path, web_ui_broadcaster).await
    } else {
        // Chapter Postern — gate static routes too when a token is set: the
        // browser gets a native Basic-Auth prompt, and a valid load plants the
        // cookie the /ws upgrade needs. The bundle is inert, but this gives the
        // login UX + cookie in one step.
        let mut set_cookie: Option<String> = None;
        if let Some(token) = auth_token {
            if !request_carries_token(&request_head, token) {
                return serve_bytes_ext(
                    stream,
                    "401 Unauthorized",
                    "text/plain; charset=utf-8",
                    "WWW-Authenticate: Basic realm=\"Aivyx Studio\"\r\n",
                    b"unauthorized: web UI auth token required",
                )
                .await;
            }
            set_cookie = Some(format!(
                "Set-Cookie: {AUTH_COOKIE}={token}; HttpOnly; SameSite=Strict; Path=/\r\n"
            ));
        }
        // Studio Gallery — proxy ComfyUI's `/view` so the browser never needs
        // to reach ComfyUI directly (it's bound to the daemon's own
        // loopback, unreachable from another LAN device). Gated by the same
        // token check above, like every other non-`/ws` route.
        if request_path(&request_head) == "/studio-asset" {
            return serve_comfy_asset(stream, &request_head, comfyui_base_url).await;
        }
        // Static HTTP: serve the embedded Dioxus bundle, falling back to the
        // legacy page at `/` while the bundle is unbuilt.
        serve_static(stream, request_path(&request_head), set_cookie.as_deref()).await
    }
}

/// The raw query string (no leading `?`) from an HTTP request line, e.g.
/// `GET /studio-asset?filename=a.png HTTP/1.1` → `filename=a.png`. Empty
/// when there's no `?`.
fn request_query(request_head: &str) -> &str {
    request_head
        .split_whitespace()
        .nth(1)
        .unwrap_or("")
        .split_once('?')
        .map(|(_, q)| q)
        .unwrap_or("")
}

/// Minimal query param lookup with `%XX` percent-decoding. No new
/// dependency: both ends of this URL (browser `<img src>` and the
/// `serve_comfy_asset` → ComfyUI request below) are ours, so a small
/// self-contained codec is simpler than promoting `url`/`urlencoding` to a
/// direct dependency for two call sites.
fn query_param(query: &str, key: &str) -> Option<String> {
    query.split('&').find_map(|kv| {
        let (k, v) = kv.split_once('=')?;
        (k == key).then(|| percent_decode(v))
    })
}

/// Reverses [`percent_encode`]: `%XX` → the decoded byte, everything else
/// passed through as-is. Invalid UTF-8 after decoding falls back to the
/// original (still-encoded) string rather than failing.
fn percent_decode(s: &str) -> String {
    // Byte-indexed throughout (never sub-slices the `&str`) so adversarial
    // input can't panic on a non-UTF-8 char boundary.
    let bytes = s.as_bytes();
    let mut out = Vec::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'%' && i + 2 < bytes.len() {
            let hi = (bytes[i + 1] as char).to_digit(16);
            let lo = (bytes[i + 2] as char).to_digit(16);
            if let (Some(hi), Some(lo)) = (hi, lo) {
                out.push((hi * 16 + lo) as u8);
                i += 3;
                continue;
            }
        }
        out.push(bytes[i]);
        i += 1;
    }
    String::from_utf8(out).unwrap_or_else(|_| s.to_string())
}

/// Percent-encodes anything outside `A-Za-z0-9-_.~` — enough for a query
/// value we're building ourselves (filenames/subfolders/type).
fn percent_encode(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for b in s.bytes() {
        if b.is_ascii_alphanumeric() || matches!(b, b'-' | b'_' | b'.' | b'~') {
            out.push(b as char);
        } else {
            out.push_str(&format!("%{b:02X}"));
        }
    }
    out
}

/// Studio Gallery — proxy `GET {COMFYUI_URL}/view?filename=&subfolder=&type=`
/// to the browser. Rejects a `filename`/`subfolder` containing `/` or `..`
/// before building the upstream request (defense in depth — ComfyUI's own
/// `/view` already validates its side, but a proxy shouldn't forward
/// anything odd upstream either).
async fn serve_comfy_asset(
    stream: tokio::net::TcpStream,
    request_head: &str,
    comfyui_base_url: Option<&str>,
) -> Result<(), DaemonError> {
    let Some(base_url) = comfyui_base_url else {
        return serve_bytes(
            stream,
            "404 Not Found",
            "text/plain; charset=utf-8",
            b"no comfyui server configured",
        )
        .await;
    };
    let query = request_query(request_head);
    let Some(filename) = query_param(query, "filename") else {
        return serve_bytes(
            stream,
            "400 Bad Request",
            "text/plain; charset=utf-8",
            b"missing filename",
        )
        .await;
    };
    let subfolder = query_param(query, "subfolder").unwrap_or_default();
    let folder_type = query_param(query, "type").unwrap_or_else(|| "output".to_string());
    if [&filename, &subfolder]
        .iter()
        .any(|s| s.contains('/') || s.contains(".."))
    {
        return serve_bytes(
            stream,
            "400 Bad Request",
            "text/plain; charset=utf-8",
            b"invalid path segment",
        )
        .await;
    }

    let url = format!(
        "{}/view?filename={}&subfolder={}&type={}",
        base_url.trim_end_matches('/'),
        percent_encode(&filename),
        percent_encode(&subfolder),
        percent_encode(&folder_type),
    );

    let resp = match reqwest::get(&url).await {
        Ok(r) if r.status().is_success() => r,
        _ => {
            return serve_bytes(
                stream,
                "502 Bad Gateway",
                "text/plain; charset=utf-8",
                b"comfyui did not return the asset",
            )
            .await;
        }
    };
    let content_type = resp
        .headers()
        .get("content-type")
        .and_then(|v| v.to_str().ok())
        .unwrap_or("application/octet-stream")
        .to_string();
    match resp.bytes().await {
        Ok(body) => serve_bytes(stream, "200 OK", &content_type, &body).await,
        Err(_) => {
            serve_bytes(
                stream,
                "502 Bad Gateway",
                "text/plain; charset=utf-8",
                b"failed reading comfyui response",
            )
            .await
        }
    }
}

/// Extract the `Origin` header value (case-insensitive name) from a peeked
/// HTTP request head, if present.
fn parse_origin(request_head: &str) -> Option<&str> {
    request_head.split("\r\n").find_map(|line| {
        line.split_once(':').and_then(|(name, value)| {
            name.trim()
                .eq_ignore_ascii_case("origin")
                .then(|| value.trim())
        })
    })
}

/// CSWSH defense for the `/ws` upgrade. Returns `true` when the connection may
/// be upgraded:
/// - no `Origin` header → a non-browser client (CLI / IPC probe / native), allowed;
/// - an `Origin` that exactly matches one of our loopback origins on `port`;
/// - an `Origin` that matches an operator-configured `extra_origins` entry
///   (Chapter Harbor `[daemon] web_ui_allowed_origins` — empty by default, so
///   the localhost-only posture is unchanged unless the operator opts in to
///   remote exposure).
///
/// Everything else — a cross-site page's real origin, a rebinding attacker's
/// hostname, or a sandboxed `null` origin — is rejected. Comparison is
/// case-insensitive and ignores a trailing slash on either side.
fn ws_origin_allowed(request_head: &str, port: u16, extra_origins: &[String]) -> bool {
    match parse_origin(request_head) {
        None => true,
        Some(origin) => {
            let origin = origin.trim_end_matches('/');
            let loopback = [
                format!("http://127.0.0.1:{port}"),
                format!("http://localhost:{port}"),
                format!("http://[::1]:{port}"),
            ];
            loopback.iter().any(|a| origin.eq_ignore_ascii_case(a))
                || extra_origins
                    .iter()
                    .any(|a| origin.eq_ignore_ascii_case(a.trim_end_matches('/')))
        }
    }
}

/// Extract the request-target path (no query string) from the HTTP request
/// line, e.g. `GET /aivyx-web_bg.wasm?v=1 HTTP/1.1` → `/aivyx-web_bg.wasm`.
fn request_path(request_line: &str) -> String {
    request_line
        .split_whitespace()
        .nth(1)
        .unwrap_or("/")
        .split('?')
        .next()
        .unwrap_or("/")
        .to_string()
}

/// Serve a static asset over plain HTTP (Chapter M.5).
///
/// `/` → the bundle's `index.html` when built, else the legacy chat page (the
/// fallback). Any other path is looked up in the embedded bundle and served
/// with its content-type; a miss is a 404.
async fn serve_static(
    stream: tokio::net::TcpStream,
    path: String,
    set_cookie: Option<&str>,
) -> Result<(), DaemonError> {
    let extra = set_cookie.unwrap_or("");
    // `/classic` always serves the legacy single-file inspection UI (audit /
    // memory / learning / proposals / notifications / sessions) — the panes the
    // Dioxus app hasn't ported yet (Chapter M ships Missions + Chat). The new
    // app links to it so building the bundle never loses a pane.
    if path == "/classic" {
        return serve_bytes_ext(
            stream,
            "200 OK",
            "text/html; charset=utf-8",
            extra,
            HTML.as_bytes(),
        )
        .await;
    }
    if path == "/" || path == "/index.html" {
        return match bundle_index() {
            Some((bytes, mime)) => serve_bytes_ext(stream, "200 OK", mime, extra, bytes).await,
            // No bundle built → the legacy page is the whole UI.
            None => {
                serve_bytes_ext(
                    stream,
                    "200 OK",
                    "text/html; charset=utf-8",
                    extra,
                    HTML.as_bytes(),
                )
                .await
            }
        };
    }
    match web_asset(&path) {
        Some((bytes, mime)) => serve_bytes_ext(stream, "200 OK", mime, extra, bytes).await,
        None => serve_bytes_ext(stream, "404 Not Found", "text/plain", extra, b"not found").await,
    }
}

/// Write one plain-HTTP response (status line + headers + body, `Connection:
/// close`). `application/wasm` etc. flow through `content_type` so the browser
/// streams + compiles the wasm correctly.
async fn serve_bytes(
    stream: tokio::net::TcpStream,
    status: &str,
    content_type: &str,
    body: &[u8],
) -> Result<(), DaemonError> {
    serve_bytes_ext(stream, status, content_type, "", body).await
}

/// Like [`serve_bytes`], but with an `extra_headers` string of raw header
/// lines (each terminated with `\r\n`, or empty) — used for `Set-Cookie` and
/// `WWW-Authenticate` on the Chapter Postern auth paths.
async fn serve_bytes_ext(
    mut stream: tokio::net::TcpStream,
    status: &str,
    content_type: &str,
    extra_headers: &str,
    body: &[u8],
) -> Result<(), DaemonError> {
    let response = format!(
        "HTTP/1.1 {status}\r\n\
         Content-Type: {content_type}\r\n\
         Content-Length: {}\r\n\
         {extra_headers}\
         Connection: close\r\n\
         \r\n",
        body.len()
    );
    stream.write_all(response.as_bytes()).await?;
    stream.write_all(body).await?;
    stream.flush().await?;
    // Graceful close. `handle_connection` only *peeks* the request line, so the
    // client's request bytes are still unread in the receive buffer. Dropping
    // the socket now would make the OS send a TCP RST instead of a FIN, and that
    // RST can race ahead and truncate a large in-flight body (e.g. the ~1.7 MB
    // wasm — small assets finish before it matters, the wasm did not, which left
    // the browser with a half-streamed module and a blank page). Half-close the
    // write side (FIN), then drain the read side to EOF so the close is clean.
    let _ = stream.shutdown().await;
    let mut sink = [0u8; 1024];
    let _ = tokio::time::timeout(std::time::Duration::from_secs(5), async {
        while let Ok(n) = stream.read(&mut sink).await {
            if n == 0 {
                break;
            }
        }
    })
    .await;
    Ok(())
}

